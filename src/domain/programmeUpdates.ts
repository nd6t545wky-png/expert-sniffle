/**
 * Hip preparation, which the warm-up barely touched.
 *
 * The mobility flow already has the ankle rock, the 90/90 switch, the adductor
 * rock, the World's Greatest Stretch and the open book — a good general flow,
 * and it stays exactly as it is. What it does not have is anything that asks
 * the hip to *produce* rotation rather than be moved through it, anything for
 * hip extension range, and anything for the lateral hip that holds the pelvis
 * level when the lead leg lands.
 *
 * That matters more for a pitcher than for most athletes. In nineteen
 * professional pitchers measured with fluid goniometry against 3-D motion
 * capture, the total rotation arc of the *non-dominant* hip — the lead leg —
 * correlated with ball velocity at r = 0.50, and the pitchers had significantly
 * less passive range on that side than on the dominant one across every
 * direction measured (Robb 2010). Nineteen subjects and a correlation is not a
 * training study, and this is not sold as one: it is a reason to spend three
 * minutes on the lead hip, not a promise of velocity.
 *
 * Deliberately no end-range adductor loading. The flow's adductor rock covers
 * that gently, and a Cossack squat in a warm-up is where a groin gets pulled.
 */
function hipPrepTask(prefix: string): SessionTask {
  return {
    id: `${prefix}-hip-prep`,
    stage: 1,
    stageTitle: "Prepare",
    stageDescription: "Raise temperature before mobility or throwing.",
    name: "Hip prep — rotation and glutes",
    prescription:
      "Half-kneeling hip flexor with posterior tilt 2 × 20 s/side · 90/90 internal rotation lift-off 6/side · lateral band walk 10 steps each way · single-leg glute bridge 8/side",
    cue: "Own the range rather than sink into it. Every rep is your own muscle moving the joint, not gravity. The lift-off uses the same 90/90 position as the switch in the flow above and does the opposite job: that one moves you through the range, this one makes you hold the end of it under your own power.",
    setup:
      "A mat or soft surface for the kneeling and bridging work, and a light band above the knees for the walks.",
    execution:
      "Half-kneeling hip flexor: back knee down, tuck the tailbone under until you feel the front of the hip, then stay tall — do not arch to get deeper. 90/90 lift-off: sit in the 90/90 position and lift the back shin off the floor without leaning, hold a second, lower under control. Lateral band walk: knees out, feet quiet, small steps. Single-leg glute bridge: drive through the heel, keep the pelvis level, no arch through the lower back.",
    rest: "Straight through — this is a warm-up, not a set.",
    stop: "Stop for groin or front-of-hip pinching. Pinching at end of range means less range today, not more effort.",
    evidence:
      "Robb 2010, Am J Sports Med — 19 professional pitchers, fluid goniometry with 3-D motion analysis. Total rotation arc of the non-dominant (lead) hip correlated with ball velocity, r = 0.50; the non-dominant hip had less passive range than the dominant one in every direction measured. Correlational, and small.",
  };
}

/**
 * Trunk and spine preparation, and the one drill here with real evidence
 * behind it.
 *
 * The warm-up prepared the shoulder, the forearm and the ankle, and left the
 * segment between them out. The gap that matters is not spinal mobility — the
 * open book covers thoracic rotation — but lumbopelvic *control*: whether the
 * pelvis holds its position when the athlete stands on one leg, which is the
 * position a pitcher is in for the whole delivery.
 *
 * That was measured prospectively in 347 professional pitchers across five
 * organisations. Pitchers whose pelvis deviated 8° or more during a single-leg
 * raise were three times more likely to miss thirty days or more to injury
 * than those under 4°, and among pitchers who did get hurt, the worst-control
 * group averaged 98.6 days missed against 43.8 (Chaudhari 2014). That is one
 * of the largest effects in the whole pitching-injury literature, and it is
 * measured on a test that costs nothing to rehearse.
 *
 * So the last drill here is deliberately the test itself, held rather than
 * scored. Bird dog and the side plank are left out on purpose — they belong to
 * the soreness protocol's lower-back prescription, and putting them in both
 * places would give a sore back the same exercise twice on the same day.
 */
function trunkPrepTask(prefix: string): SessionTask {
  return {
    id: `${prefix}-trunk-prep`,
    stage: 1,
    stageTitle: "Prepare",
    stageDescription: "Raise temperature before mobility or throwing.",
    name: "Trunk and spine prep",
    prescription:
      "Cat-camel 8 slow · dead bug 6/side · single-leg pelvic-control hold 2 × 20 s/side",
    cue: "The last one is the one that counts. Pelvis dead level, and nothing above the hips moves.",
    setup: "A mat for the first two. For the hold, stand tall with something at hand's reach to touch if you wobble.",
    execution:
      "Cat-camel: move one segment at a time, slowly, through the whole spine — this is motion, not a stretch. Dead bug: press the lower back into the floor and keep it there as the opposite arm and leg reach away; the moment the back lifts, you have found your range. Single-leg pelvic-control hold: come to the single-leg stance you pitch from and hold with the pelvis level — no hip drop, no tilt, no arch. Watch the front of your hips in a mirror or a window if you have one.",
    rest: "No rest needed. Move on when the last hold is clean.",
    stop: "Stop for lower-back pain rather than working through it, and report it on the daily plan so tomorrow is adjusted.",
    evidence:
      "Chaudhari 2014, Am J Sports Med 42(11):2734–2740 — prospective, 347 professional pitchers across five organisations. Pelvic deviation ≥8° on a single-leg raise carried a 3.0× risk of missing 30+ days versus <4°; among those injured, that group averaged 98.6 days missed against 43.8 in the best-controlled group.",
  };
}

/**
 * Sprint drills, on the day that sprints without any.
 *
 * Three days in the programme contain sprinting and they are not equivalent:
 *
 *   - **Wednesday** — "Sprint mechanics": A-march, ankling and three
 *     progressive starts. That *is* a sprint warm-up, and a good one.
 *   - **Friday/Saturday/Sunday** — "Sprint build-ups": 2 × 10 m, 2 × 20 m,
 *     final rep about 90%. A ramp, on a day the athlete may pitch. Adding
 *     running in front of a game buys nothing and costs legs.
 *   - **Tuesday** — "Acceleration quality": 2 × 10 m build-up straight into
 *     3 × 20 m at 85–90%. The fastest running of the week, off a warm-up with
 *     no sprint drills in it at all.
 *
 * So only Tuesday gets this, and the rule is written as a condition rather
 * than a weekday: a session with speed work and no drills of its own. If the
 * speed day ever moves, the preparation moves with it.
 *
 * Deliberately **no build-ups**. The speed task already prescribes its own
 * 10 m ramp; adding a second one would repeat it and put another hundred
 * metres of running in front of a session that is followed by 45–55 throws.
 * What is missing is the rehearsal, not the ramp.
 */
function sprintPrepTask(prefix: string): SessionTask {
  return {
    id: `${prefix}-sprint-prep`,
    stage: 1,
    stageTitle: "Prepare",
    stageDescription: "Raise temperature before mobility or throwing.",
    name: "Sprint drills — before the build-ups",
    prescription:
      "Leg swings forward–back 10/side · leg swings lateral 10/side · A-skip 2 × 15 m · ankle dribble 2 × 15 m",
    cue: "Rehearse the shapes slowly so the build-ups below are the first fast running, not the first running. The 10 m build-ups in the speed set are still your ramp — this does not replace them.",
    setup: "About 20 m of flat, even ground. Trainers, not spikes.",
    execution:
      "Leg swings: hold something solid and swing through a range you control — no ballistic end-range. A-skip: tall, knee up, foot down underneath the hip, quick off the ground. Ankle dribble: knees almost straight, feet cycling low and fast underneath you — this is the one that teaches the foot to land under the hip rather than out in front, which is where a hamstring gets caught at speed.",
    rest: "Walk back between reps. None of this should raise your breathing much.",
    stop: "Any hamstring twinge ends the sprinting for the day, and report it on the plan. That is a warning, not a niggle to run off.",
    evidence:
      "van Dyk 2019, BJSM 53:1362–1370 — meta-analysis, 15 studies, 8,459 athletes: injury-prevention programmes including the Nordic hamstring exercise roughly halved hamstring injury rates (RR 0.49, 95% CI 0.32–0.74). That is the evidence for the Nordic already in Monday's session, not for these drills. Warm-up drills rehearse the pattern and raise tissue temperature; the evidence that drills alone prevent anything is thin, and the Nordic finding itself has been challenged on methodological grounds (Impellizzeri 2021).",
  };
}

/** Speed work with no drill preparation of its own. */
function needsSprintDrills(tasks: SessionTask[]): boolean {
  const hasSpeedWork = tasks.some((task) => task.stageTitle === "Speed");
  const hasDrills = tasks.some((task) =>
    /A-march|ankling|sprint mechanics|sprint build-ups|sprint drills/i.test(task.name + task.prescription)
  );
  return hasSpeedWork && !hasDrills;
}

export function applyBaselineProgramming(
  session: Session,
  level: ReducedLevel | null = null,
  day: number | null = null
): Session {
  const tasks = session.tasks
    .filter((task) => !isRemovedImplement(task))
    .filter((task) => !isDisplacedByBackSquat(task, day))
    .map(withBarSpeedIntent)
    .map(withPlyoEvidence)
    .map(withSupersets(day))
    .map(withExplicitReducedDose(level));

  // Warm-up additions run every day that has a warm-up. Sunday has no
  // Prepare stage and correctly receives nothing.
  const prepEnd = tasks.map((task) => task.stageTitle).lastIndexOf("Prepare");
  if (prepEnd !== -1) {
    const prepPrefix = String(tasks[0].id).split("-").slice(0, 2).join("-");
    const absent = (addition: SessionTask) => !tasks.some((task) => task.id === addition.id);
    const regional = [hipPrepTask(prepPrefix), trunkPrepTask(prepPrefix)].filter(absent);
    // The warm-up ends with whatever prepares the stage that follows it. That
    // is the arm on every day except the speed day, where the sprinting comes
    // first and the drills belong last instead.
    const tail = [
      ankleStiffnessTask(prepPrefix),
      forearmPrepTask(prepPrefix),
      ...(needsSprintDrills(tasks) ? [sprintPrepTask(prepPrefix)] : []),
    ].filter(absent);

    // Order is general to specific, and it is not cosmetic. The stage after
    // this one is always throwing or sprinting, so what the athlete does last
    // is what carries into the first throw.
    //
    // The two regional blocks go in beside the general mobility flow, *not* at
    // the end of the stage. Appended, they landed between "Scapular and cuff
    // activation" and the throwing — putting six minutes of hip and trunk work
    // between the shoulder being primed and the first ball leaving the hand,
    // and displacing the most throwing-specific piece of the warm-up into the
    // middle of it.
    //
    // Two inserts rather than one, later index first so the earlier splice
    // does not shift it:
    //
    //   raise → general mobility → hips → trunk → cuff → ankle → forearm
    tasks.splice(prepEnd + 1, 0, ...tail);

    const flowIndex = tasks.findIndex(
      (task) => task.stageTitle === "Prepare" && /mobility flow/i.test(task.name)
    );
    tasks.splice(flowIndex === -1 ? prepEnd + 1 : flowIndex + 1, 0, ...regional);
  }

  // Read off the task ids, like the velocity policy: there are eighty-odd call
  // sites for this function and a fourth parameter would have been forgotten
  // by most of them.
  const week = weekFromTasks(tasks);

  const gymIndex = tasks.findIndex((task) => GYM_STAGE_TITLES.includes(task.stageTitle));

  // Thursday carries no gym stage at all, which is exactly why it was chosen
  // for the microdose — but it means there is no stage to insert into.
  //
  // The stage is synthesised as *values*, not as a task. It used to be a real
  // task called "Microdose block", prescribed "One movement, done well" —
  // scaffolding that existed only to carry the stage title and the id prefix,
  // and that reached the athlete as a tickable row naming no movement, no sets
  // and no reps. There was never a second thing to do: the hinge below is the
  // microdose, and it now says so itself.
  const synthesised = gymIndex === -1;
  if (synthesised && day !== DAY_THURSDAY) return withVelocityPolicy(session, tasks, level);

  const stageTitle = synthesised ? "Whole-Body Force" : tasks[gymIndex].stageTitle;
  const stageDescription = synthesised
    ? "Microdose — one hinge, kept cheap so it does not compete with recovery."
    : tasks[gymIndex].stageDescription;
  const prefix = String((synthesised ? tasks[0]?.id : tasks[gymIndex].id) ?? "day")
    .split("-")
    .slice(0, 2)
    .join("-");
  /** Where a synthesised stage begins, or the existing gym stage's head. */
  const stageAt = synthesised ? tasks.filter((task) => task.stage <= 4).length : gymIndex;

  // The primer's broad jump trains the slow SSC the athlete already has.
  // Swap it for the depth jump the report asked for, keeping the med-ball
  // throw so the primer remains a primer.
  const primerIndex = tasks.findIndex((task) => /primer/i.test(task.name));
  if (primerIndex !== -1) {
    const primer = tasks[primerIndex];
    tasks[primerIndex] = {
      ...primer,
      prescription: primer.prescription.replace(/·?\s*broad jump[^·]*/i, "").replace(/·\s*$/, "").trim(),
      cue: appendOnce(
        primer.cue,
        "Broad jumps were replaced by depth jumps below: testing flagged fast stretch-shortening, not horizontal power, as the limiter."
      ),
    };
  }

  // Placement is not cosmetic here. Reactive and velocity work has to happen
  // while the athlete is fresh: a depth jump after a heavy deadlift trains a
  // slow contact, which is the exact quality the testing flagged as the
  // limiter. So these go early — right behind the primer, ahead of the heavy
  // strength work — and only the hinge goes at the end with the accessories.
  // A null day means "wherever this session is" — used by tests and by any
  // caller that has not said. It gets everything, as before.
  const onMonday = day === null || day === DAY_MONDAY;
  const onWednesday = day === null || day === DAY_WEDNESDAY;
  const onThursday = day === null || day === DAY_THURSDAY;

  const early = [
    ...(onMonday ? [depthJumpTask(prefix, stageTitle, stageDescription)] : []),
    ...(onWednesday ? [velocitySquatTask(prefix, stageTitle, stageDescription)] : []),
    // Heavy strength follows the velocity work: light-and-fast first, then
    // load. The reverse order leaves the fast work fatigued.
    ...(onMonday ? [backSquatTask(prefix, stageTitle, stageDescription, week, weekFocus(week))] : []),
  ]
    // The report asked for bar-speed intent on the primary strength lifts, and
    // the back squat is the primary strength lift it asked to add. Annotating
    // it here rather than leaving it out is also what makes a second pass
    // agree with the first: on that pass the squat is an ordinary task in the
    // input and would pick the cue up anyway.
    .map(withBarSpeedIntent)
    .filter((addition) => !tasks.some((task) => task.id === addition.id));

  // The hinge, then the calf. Both are microdoses and neither competes with
  // the other: one is a posterior-chain lift, the other is local ankle work.
  const late = (
    onThursday
      ? [rdlTask(prefix, stageTitle, stageDescription), soleusTask(prefix, stageTitle, stageDescription)]
      : []
  ).filter((addition) => !tasks.some((task) => task.id === addition.id));

  // On a synthesised stage there is nothing to sit behind, so the hinge opens
  // it: `stageAt - 1` makes the splice below land exactly on `stageAt`.
  let lastGym = synthesised ? stageAt - 1 : gymIndex;
  for (let i = tasks.length - 1; i >= 0; i -= 1) {
    if (GYM_STAGE_TITLES.includes(tasks[i].stageTitle)) {
      lastGym = i;
      break;
    }
  }
  tasks.splice(lastGym + 1, 0, ...late);

  // After whatever prepares for it: the named primer on Monday, the jumps on
  // Wednesday. The jumps are the most neurally demanding thing in that
  // session and have to come first, so the speed squat follows them rather
  // than displacing them.
  const anchor = tasks.findIndex((task) => /primer/i.test(task.name) || /broad jump/i.test(task.name));
  tasks.splice(anchor === -1 ? stageAt : anchor + 1, 0, ...early);

  return withVelocityPolicy(session, tasks, level);
}

/**
 * The week's velocity policy, applied last on every exit from this function.
 *
 * Last because every intent change it makes is a `min` against what is already
 * written, so it cannot be undone by a later rewrite and running it twice
 * changes nothing. And on *every* exit rather than at the call site, because
 * there are two returns here and a cap that applies on one of them is not a
 * cap.
 *
 * The week comes off the task ids rather than from an argument. There are
 * eighty-odd call sites for this function across the app and its tests; a
 * fourth parameter would have been forgotten by most of them, and the failure
 * would have been silent.
 */
/**
 * What the week's own plan calls this week — "Force peak", "Deload and assess".
 *
 * Only the deload/taper/review wording is read from it, and only to change how
 * the squat is *described*: the numbers come from the block table either way,
 * so a week plan that cannot be built costs a sentence, not a prescription.
 */
function weekFocus(week: number | null): string | null {
  if (week === null) return null;
  try {
    return String(weekPlan(week).focus ?? "") || null;
  } catch {
    return null;
  }
}

function withVelocityPolicy(session: Session, tasks: SessionTask[], level: ReducedLevel | null): Session {
  return applyVelocityPolicy(
    { ...session, tasks },
    { week: weekFromTasks(tasks), reduced: level !== null }
  );
}
