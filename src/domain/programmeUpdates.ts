/**
 * Bar-speed intent cueing on primary strength lifts.
 *
 * The report calls this out explicitly to address a 354 ms time to peak
 * force. It changes nothing about the load or the set count — only what the
 * athlete is trying to do with the bar — so it is applied as an annotation
 * rather than as a new prescription.
 */
const BAR_SPEED_LIFTS = ["deadlift", "squat", "bench press", "push press"];

/**
 * Lifts that match the list above but must not carry the cue.
 *
 * The speed squat is already prescribed as maximal intent at a fixed light
 * load, so the cue would repeat its own prescription. The microdoses are the
 * opposite case and the more important one: Thursday's RDL is deliberately
 * sub-maximal, twenty-four hours from a game block, and telling the athlete to
 * drive the bar maximally there is the wrong instruction on the wrong day.
 */
const NO_BAR_SPEED_INTENT = [/speed squat/i, /microdose/i];

function withBarSpeedIntent(task: SessionTask): SessionTask {
  const name = task.name.toLowerCase();
  if (!BAR_SPEED_LIFTS.some((lift) => name.includes(lift))) return task;
  if (NO_BAR_SPEED_INTENT.some((pattern) => pattern.test(task.name))) return task;
  return {
    ...task,
    cue: appendOnce(
      task.cue,
      "Move the bar with maximal intent on every concentric, even at heavy loads — testing flagged a slow 354 ms time to peak force."
    ),
    execution: appendOnce(
      task.execution,
      "Intent matters as much as the load here: the bar should be driven, not lifted."
    ),
  };
}

/**
 * Evidence note carried by every plyo-ball task.
 *
 * Weighted-ball throwing is the least settled part of this programme. A
 * randomised trial of high-school pitchers (Reinold et al., 2018) reported a
 * 24% injury rate in the weighted-ball group against none in the control,
 * along with a 4.3° gain in shoulder external rotation; an interim study of
 * 88 minor-league pitchers (2025) found higher arm and trunk injury
 * prevalence (39.1% vs 23.8%) and roughly double the days lost among users.
 *
 * That evidence does not make sub-maximal constraint work indefensible —
 * which is how most of these throws are prescribed here — but it does mean
 * the athlete should see it rather than have it decided for them.
 */
export const PLYO_EVIDENCE_NOTE =
  "Evidence note: weighted-ball throwing is contested. A randomised trial of high-school pitchers (Reinold et al., 2018) found a 24% injury rate in the weighted-ball group versus none in the control, alongside a 4.3° increase in shoulder external rotation. An interim 2025 study of 88 minor-league pitchers found higher arm and trunk injury prevalence (39.1% vs 23.8%) and about twice the days lost among users. Risk concentrates in maximal-intent light-ball throwing rather than sub-maximal constraint work. Review this block with your coach and medical team before progressing intent or volume.";

function withPlyoEvidence(task: SessionTask): SessionTask {
  if (task.stageTitle !== "Plyo Ball Preparation") return task;
  // The 2 kg ball had its own note; it is now removed outright, so the only
  // remaining caveat is the light-ball one.
  const light = /1[0-2]?[05]\s*g\b/.test(task.name) && !/1,?000\s*g/.test(task.name);
  const extra = light
    ? " Light balls produce the highest arm speeds and are where the reported injury risk concentrates."
    : "";
  return { ...task, stop: appendOnce(task.stop, `${PLYO_EVIDENCE_NOTE}${extra}`) };
}

/**
 * Apply everything to a built session.
 *
 * Order matters only in that the additions land inside the gym stage, so
 * they inherit its heading and stay grouped with the rest of the lift.
 */
/**
 * State the reduced dose instead of describing how to compute it.
 *
 * The programme replaces a prescription with guidance when readiness drops —
 * "Remove the final work set · use no more than 90% of the listed load".
 * That is arithmetic handed to a fatigued athlete mid-session. The numbers
 * come first now, with the rule that produced them kept underneath so the
 * reasoning is still visible and the original is still one tap away.
 */
function withExplicitReducedDose(level: ReducedLevel | null) {
  return (task: SessionTask): SessionTask => {
    if (!level || !task.adapted) return task;
    // A second pass would read its own output back as the "original" — the
    // note it leaves behind is itself of the form the parser accepts — and
    // reduce an already-reduced dose again.
    if (typeof task.adaptationNote === "string" && task.adaptationNote.includes("· Reduced to ")) {
      return task;
    }
    const original = originalPrescription(task.adaptationNote);
    if (!original) return task;

    const kind = prescriptionKind(task.stageTitle, task.name);
    const explicit = reduceSetsAndReps(original, kind, level);
    // Nothing parseable means nothing to state. Guessing a set count here
    // would be worse than leaving the guidance the programme wrote.
    if (!explicit) return task;

    return {
      ...task,
      prescription: explicit,
      cue: `${REDUCTION_RULES[level][kind]} ${task.cue}`,
      adaptationNote: `${task.adaptationNote} · Reduced to ${explicit}.`,
    };
  };
}


/**
 * The 2 kg plyo ball, removed at the athlete's request.
 *
 * It appeared once — Monday's reverse throw, 1 × 5 at 50% — as low-intent
 * patterning work. It goes for two reasons. It is heavier than any implement
 * used in the injury and velocity trials this programme cites (Reinold's RCT
 * topped out at 32 oz / 907 g; the 2025 professional cohort reported 4–9 oz),
 * so there is no evidence base for that specific load. And the 1,000 g
 * reverse throw immediately after it does the same job, which means nothing
 * has to be invented to replace it.
 *
 * Kept as a named rule rather than an edit to the extracted programme:
 * `programmeContent.ts` is regenerated from the frozen v60 snapshot, so an
 * edit there would be silently undone on the next extraction.
 */
const REMOVED_IMPLEMENTS = [/2,?000\s*g/];

function isRemovedImplement(task: SessionTask): boolean {
  return task.stageTitle === "Plyo Ball Preparation"
    && REMOVED_IMPLEMENTS.some((pattern) => pattern.test(task.name));
}

/**
 * The trap bar deadlift comes off Monday.
 *
 * Once the tested back squat is in at 77–87%, Monday carries two heavy
 * bilateral primaries back to back — roughly twenty heavy squat reps and
 * twelve heavy pulls of axial load, on a day that also throws 45–60 balls.
 * Neither lift progresses cleanly when they compete for the same recovery,
 * and the trap bar's 6 × 2 only does its job if the bar moves fast, which it
 * will not do behind a squat at 87%.
 *
 * The hinge is not lost: the RDL is on Thursday and the single-leg RDL on
 * Wednesday, so the pattern is covered twice a week. The squat pattern was
 * covered zero times before the testing added it. And the trap bar itself
 * survives on Wednesday as the jump variant, where its speed-strength intent
 * is actually preserved.
 */
function isDisplacedByBackSquat(task: SessionTask, day: number | null): boolean {
  return day === DAY_MONDAY && /^Trap bar deadlift$/.test(task.name);
}


// --- Weekly distribution ----------------------------------------------------

/**
 * Where each addition belongs in the week.
 *
 * Everything the testing called for was landing on Monday, which already
 * carried seven lifts, while Tuesday ran speed work only and Thursday carried
 * no loading at all. That is not a programme, it is one hard day and three
 * light ones — and it is the opposite of what the MFT profile suggested, which
 * was that this athlete tolerates frequency.
 *
 * So the work is spread:
 *
 *  Monday    reactive + heavy strength. The primary force day.
 *  Wednesday bar-speed work. Wednesday is already the power day — med-ball,
 *            jumps, push press — so the speed squat belongs with them, not
 *            stacked behind Monday's heavy squat.
 *  Thursday  the posterior-chain hinge, as a microdose. Thursday had no
 *            loading whatsoever, and an RDL is cheap systemically: it fits
 *            beside recovery work without competing with it.
 *
 * Friday is left alone — it is the pre-game microdose and already exists.
 * Saturday is competition, Sunday is rest.
 */
const DAY_MONDAY = 0;
const DAY_WEDNESDAY = 2;
const DAY_THURSDAY = 3;

// --- Supersets --------------------------------------------------------------

/**
 * Pairs that should be run together, and — just as important — what must not.
 *
 * Antagonist and non-competing pairs cost nothing in quality and buy back a
 * lot of session time, which is the difference between an eleven-item Monday
 * being done and being abandoned halfway.
 *
 * Nothing that depends on being fresh is paired: the heavy squat, the trap
 * bar, the depth jump and the speed squat all run straight, because density
 * degrades exactly the qualities they train. A superset there would quietly
 * convert strength and power work into conditioning.
 */
const SUPERSET_RULES: { day: number; group: string; members: RegExp[] }[] = [
  {
    day: DAY_MONDAY,
    group: "A",
    members: [/^Bench press$/, /^Chest-supported dumbbell row$/],
  },
  {
    day: DAY_MONDAY,
    group: "B",
    members: [/^Nordic hamstring curl$/, /Pallof press/],
  },
  {
    day: DAY_WEDNESDAY,
    group: "A",
    members: [/^Push press$/, /^Chin-up$/],
  },
  {
    day: DAY_WEDNESDAY,
    group: "B",
    members: [/Single-leg Romanian deadlift/, /cable chop/i],
  },
];

/** Movements that must never be paired, whatever else is going on. */
const NEVER_SUPERSET = [/Back squat/, /Speed squat/, /Depth jump/, /Trap bar/];

function withSupersets(day: number | null) {
  return (task: SessionTask): SessionTask => {
    if (day === null) return task;
    if (NEVER_SUPERSET.some((pattern) => pattern.test(task.name))) return task;

    const rule = SUPERSET_RULES.find(
      (candidate) => candidate.day === day && candidate.members.some((m) => m.test(task.name))
    );
    if (!rule) return task;

    const position = rule.members.findIndex((m) => m.test(task.name)) + 1;
    const partners = rule.members.length;
    return {
      ...task,
      superset: `${rule.group}${position}`,
      supersetOf: partners,
      rest:
        position < partners
          ? "No rest — go straight into the next movement in this superset."
          : appendOnce(task.rest, `Rest here, then return to ${rule.group}1.`),
    };
  };
}


